#!/usr/bin/env python3
"""
cv_fold_sizes.py
----------------
Fold sizes for Appendix E (`tbl-cv-sizes`), which is a hardcoded table and so
has to be regenerated by hand whenever the item set changes.

Replicates the fold construction in by_layer_mlp.py exactly, including the seed
and the modulo assignment, rather than computing the idealised n/10 and n/100.
The word-held-out numbers in particular cannot be derived analytically: a
binomial enters fold k's test set only if BOTH its words fall in word-fold k,
and the training set only if NEITHER does, so the counts depend on how the
vocabulary happens to partition.

Run with base conda, not PRenv (see the spearmanr DLL crash).

Usage
-----
  python Scripts/corpus/cv_fold_sizes.py
  python Scripts/corpus/cv_fold_sizes.py --harvest Data/carrier_sentences.csv
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
BASE = HERE.parents[1]
SEED = 964          # by_layer_mlp.SEED
FOLDS = 10          # by_layer_mlp.FOLDS


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--harvest", default=str(BASE / "Data" / "carrier_sentences.csv"))
    p.add_argument("--set", default="novel", dest="which")
    args = p.parse_args()

    hv = pd.read_csv(args.harvest)
    hv = hv[(hv["set"] == args.which)
            & hv["sent_1"].notna() & hv["sent_2"].notna()]
    hv = hv[hv["word1"] != hv["word2"]]
    w1 = hv["word1"].astype(str).values
    w2 = hv["word2"].astype(str).values
    n = len(hv)
    words = np.array(sorted(set(w1) | set(w2)))
    print(f"{args.which}: {n:,} binomials over {len(words):,} unique words\n")

    rng = np.random.default_rng(SEED)

    # pair_novel: items assigned to folds directly.
    perm = rng.permutation(n) % FOLDS
    tr = [(perm != k).sum() for k in range(FOLDS)]
    te = [(perm == k).sum() for k in range(FOLDS)]
    print("Binomial-held-out")
    print(f"  train / fold : {min(tr):,} - {max(tr):,}")
    print(f"  test  / fold : {min(te):,} - {max(te):,}")
    print("  discarded    : 0\n")

    # word_novel: the VOCABULARY is partitioned; a pair is testable only if both
    # of its words land in the same held-out fold.
    wperm = rng.permutation(len(words)) % FOLDS
    wf = {w: int(wperm[i]) for i, w in enumerate(words)}
    f1 = np.array([wf[w] for w in w1])
    f2 = np.array([wf[w] for w in w2])
    wtr, wte, wdc = [], [], []
    for k in range(FOLDS):
        te_m = (f1 == k) & (f2 == k)
        tr_m = (f1 != k) & (f2 != k)
        wte.append(int(te_m.sum()))
        wtr.append(int(tr_m.sum()))
        wdc.append(int(n - te_m.sum() - tr_m.sum()))
    print("Word-held-out")
    print(f"  train / fold     : {min(wtr):,} - {max(wtr):,}")
    print(f"  test  / fold     : {min(wte):,} - {max(wte):,}")
    print(f"  discarded / fold : {min(wdc):,} - {max(wdc):,} "
          f"({np.mean(wdc) / n:.1%} mean)\n")

    print("tbl-cv-sizes rows:")
    print(f'  "Binomial-held-out",  "{min(tr):,}--{max(tr):,}", '
          f'"{min(te):,}--{max(te):,}", "0"')
    print(f'  "Word-held-out",      "{min(wtr):,}--{max(wtr):,}", '
          f'"{min(wte):,}--{max(wte):,}", '
          f'"{min(wdc):,}--{max(wdc):,} ({np.mean(wdc)/n:.1%})"')
    print(f"\n  caption counts: {n:,} binomials over {len(words):,} unique words")


if __name__ == "__main__":
    main()
